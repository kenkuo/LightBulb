using System;
using System.Buffers.Binary;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;

namespace LightBulb.Core;

public static class Mhc2Profile
{
    private const uint Mhc2 = 0x4D484332;
    private static readonly double[,] SrgbToXyz =
    {
        { 0.4124564, 0.3575761, 0.1804375 },
        { 0.2126729, 0.7151522, 0.0721750 },
        { 0.0193339, 0.1191920, 0.9503041 },
    };

    public static byte[] Create(
        ReadOnlySpan<byte> originalProfile,
        HdrDisplayMetadata metadata,
        ColorConfiguration configuration,
        string description
    )
    {
        var tags = new Dictionary<uint, byte[]>();
        byte[] header;
        if (originalProfile.IsEmpty)
        {
            header = CreateHeader();
            AddDisplayMetadata(tags, metadata);
            tags.Add(Signature("cprt"), TextTag("Generated by LightBulb."));
            var curve = new byte[12 + 256 * 2];
            WriteUInt(curve, 0, Signature("curv"));
            WriteUInt(curve, 8, 256);
            for (var i = 0; i < 256; i++)
                BinaryPrimitives.WriteUInt16BigEndian(
                    curve.AsSpan(12 + i * 2),
                    (ushort)Math.Round(DecodeSrgb(i / 255.0) * ushort.MaxValue)
                );
            foreach (var name in new[] { "rTRC", "gTRC", "bTRC" })
                tags.Add(Signature(name), curve);
        }
        else
        {
            header = ReadProfile(originalProfile, tags);
            AddDisplayMetadata(tags, metadata);
        }

        tags.TryGetValue(Mhc2, out var originalCalibration);
        tags[Mhc2] = CreateCalibration(originalCalibration, metadata, configuration);
        tags[Signature("desc")] =
            header[8] >= 4 ? MultilingualTextTag(description) : DescriptionTag(description);

        var size = 132 + tags.Count * 12 + tags.Values.Sum(t => Align(t.Length));
        var profile = new byte[size];
        header.CopyTo(profile, 0);
        WriteUInt(profile, 0, (uint)size);
        WriteUInt(profile, 128, (uint)tags.Count);
        var index = 132;
        var offset = 132 + tags.Count * 12;
        foreach (var (signature, tag) in tags)
        {
            WriteUInt(profile, index, signature);
            WriteUInt(profile, index + 4, (uint)offset);
            WriteUInt(profile, index + 8, (uint)tag.Length);
            tag.CopyTo(profile, offset);
            index += 12;
            offset += Align(tag.Length);
        }

        // ICC profile IDs use MD5 by specification, not as a security checksum.
        var idInput = (byte[])profile.Clone();
        idInput.AsSpan(44, 4).Clear();
        idInput.AsSpan(64, 4).Clear();
        idInput.AsSpan(84, 16).Clear();
        MD5.HashData(idInput).CopyTo(profile, 84);
        return profile;
    }

    private static byte[] ReadProfile(ReadOnlySpan<byte> profile, Dictionary<uint, byte[]> tags)
    {
        if (
            profile.Length < 132
            || ReadUInt(profile, 0) > profile.Length
            || ReadUInt(profile, 0) < 132
            || ReadUInt(profile, 36) != Signature("acsp")
            || ReadUInt(profile, 12) != Signature("mntr")
            || ReadUInt(profile, 16) != Signature("RGB ")
            || profile[8] is not (2 or 4)
        )
            throw new InvalidDataException(
                "The existing HDR profile is not a supported RGB display ICC profile."
            );

        var size = (int)ReadUInt(profile, 0);
        var count = ReadUInt(profile, 128);
        if (132L + count * 12L > size)
            throw new InvalidDataException("The existing ICC profile has a truncated tag table.");

        for (var i = 0; i < count; i++)
        {
            var index = 132 + i * 12;
            var signature = ReadUInt(profile, index);
            var offset = ReadUInt(profile, index + 4);
            var length = ReadUInt(profile, index + 8);
            if (offset < 132 + count * 12L || (long)offset + length > size || length < 8)
                throw new InvalidDataException(
                    "The existing ICC profile contains an invalid tag offset."
                );
            if (!tags.TryAdd(signature, profile.Slice((int)offset, (int)length).ToArray()))
                throw new InvalidDataException("The existing ICC profile contains duplicate tags.");
        }

        return profile[..128].ToArray();
    }

    private static byte[] CreateCalibration(
        byte[]? original,
        HdrDisplayMetadata metadata,
        ColorConfiguration configuration
    )
    {
        var matrix = Identity();
        var minimum = metadata.MinimumLuminance;
        var peak = metadata.PeakLuminance;
        var count = 0;
        var luts = new byte[3][];
        if (original is not null)
        {
            if (original.Length < 36 || ReadUInt(original, 0) != Mhc2)
                throw new InvalidDataException("The existing profile has an invalid MHC2 tag.");
            count = checked((int)ReadUInt(original, 8));
            if (count is < 0 or > 4096)
                throw new InvalidDataException("The existing MHC2 LUT is too large.");
            minimum = ReadFixed(original, 12);
            peak = ReadFixed(original, 16);
            var matrixOffset = ReadUInt(original, 20);
            if (matrixOffset != 0)
            {
                CheckRange(original, matrixOffset, 48);
                for (var row = 0; row < 3; row++)
                for (var column = 0; column < 3; column++)
                    matrix[row, column] = ReadFixed(
                        original,
                        (int)matrixOffset + (row * 4 + column) * 4
                    );
            }

            for (var channel = 0; channel < 3; channel++)
            {
                var lutOffset = ReadUInt(original, 24 + channel * 4);
                if (count == 0)
                {
                    luts[channel] = [];
                    continue;
                }
                CheckRange(original, lutOffset, 8 + count * 4);
                if (ReadUInt(original, (int)lutOffset) != Signature("sf32"))
                    throw new InvalidDataException(
                        "The existing MHC2 LUT has an unsupported encoding."
                    );
                luts[channel] = original.AsSpan((int)lutOffset, 8 + count * 4).ToArray();
            }
        }
        else
        {
            Array.Fill(luts, Array.Empty<byte>());
        }

        if (!double.IsFinite(minimum) || !double.IsFinite(peak) || minimum < 0 || peak <= minimum)
            throw new InvalidDataException(
                "HDR luminance metadata is missing or invalid. Calibrate the display in Windows first."
            );

        var (red, green, blue) = configuration.GetGammaMultipliers();
        var gains = new double[,]
        {
            { DecodeSrgb(red), 0, 0 },
            { 0, DecodeSrgb(green), 0 },
            { 0, 0, DecodeSrgb(blue) },
        };
        // MHC2 matrices act on linear CIEXYZ, not on PQ-encoded HDR values.
        // Apply the filter before the existing calibration and leave its output LUTs intact.
        var adjustment = Multiply(Multiply(SrgbToXyz, gains), Invert(SrgbToXyz));
        matrix = Multiply(matrix, adjustment);
        var data = new byte[84 + luts.Sum(l => l.Length)];
        WriteUInt(data, 0, Mhc2);
        WriteUInt(data, 8, (uint)count);
        WriteFixed(data, 12, minimum);
        WriteFixed(data, 16, peak);
        WriteUInt(data, 20, 36);
        for (var row = 0; row < 3; row++)
        for (var column = 0; column < 3; column++)
            WriteFixed(data, 36 + (row * 4 + column) * 4, matrix[row, column]);

        var offset = 84;
        for (var channel = 0; channel < 3; channel++)
        {
            if (count == 0)
                continue;
            WriteUInt(data, 24 + channel * 4, (uint)offset);
            luts[channel].CopyTo(data, offset);
            offset += luts[channel].Length;
        }

        return data;
    }

    private static void AddDisplayMetadata(
        Dictionary<uint, byte[]> tags,
        HdrDisplayMetadata metadata
    )
    {
        if (
            new[] { "rXYZ", "gXYZ", "bXYZ", "wtpt", "lumi" }.All(n =>
                tags.ContainsKey(Signature(n))
            )
        )
            return;

        double[] Xyz(double x, double y)
        {
            if (!double.IsFinite(x) || !double.IsFinite(y) || x < 0 || y <= 0 || x + y > 1.0001)
                throw new InvalidDataException(
                    "HDR color primaries are missing or invalid. Calibrate the display in Windows first."
                );
            return [x / y, 1, (1 - x - y) / y];
        }

        var red = Xyz(metadata.RedX, metadata.RedY);
        var green = Xyz(metadata.GreenX, metadata.GreenY);
        var blue = Xyz(metadata.BlueX, metadata.BlueY);
        var white = Xyz(metadata.WhiteX, metadata.WhiteY);
        var primaries = new double[,]
        {
            { red[0], green[0], blue[0] },
            { red[1], green[1], blue[1] },
            { red[2], green[2], blue[2] },
        };
        var inverse = Invert(primaries);
        var scale = Enumerable
            .Range(0, 3)
            .Select(row =>
                Enumerable.Range(0, 3).Sum(column => inverse[row, column] * white[column])
            )
            .ToArray();
        if (scale.Any(s => !double.IsFinite(s) || s <= 0))
            throw new InvalidDataException(
                "HDR display primaries do not form a valid color space."
            );
        var colors = new[] { red, green, blue };
        var names = new[] { "rXYZ", "gXYZ", "bXYZ" };
        for (var i = 0; i < 3; i++)
            tags.TryAdd(
                Signature(names[i]),
                XyzTag(colors[i][0] * scale[i], scale[i], colors[i][2] * scale[i])
            );
        tags.TryAdd(Signature("wtpt"), XyzTag(white[0], white[1], white[2]));
        if (!double.IsFinite(metadata.FullFrameLuminance) || metadata.FullFrameLuminance <= 0)
            throw new InvalidDataException(
                "HDR full-frame luminance is missing. Calibrate the display in Windows first."
            );
        tags.TryAdd(Signature("lumi"), XyzTag(0, metadata.FullFrameLuminance, 0));
    }

    private static byte[] CreateHeader()
    {
        var header = new byte[128];
        WriteUInt(header, 8, 0x02400000);
        WriteUInt(header, 12, Signature("mntr"));
        WriteUInt(header, 16, Signature("RGB "));
        WriteUInt(header, 20, Signature("XYZ "));
        var now = DateTime.UtcNow;
        var date = new[] { now.Year, now.Month, now.Day, now.Hour, now.Minute, now.Second };
        for (var i = 0; i < date.Length; i++)
            BinaryPrimitives.WriteUInt16BigEndian(header.AsSpan(24 + i * 2), (ushort)date[i]);
        WriteUInt(header, 36, Signature("acsp"));
        WriteUInt(header, 40, Signature("MSFT"));
        WriteFixed(header, 68, 0.9642);
        WriteFixed(header, 72, 1);
        WriteFixed(header, 76, 0.8249);
        return header;
    }

    private static byte[] XyzTag(double x, double y, double z)
    {
        var data = new byte[20];
        WriteUInt(data, 0, Signature("XYZ "));
        WriteFixed(data, 8, x);
        WriteFixed(data, 12, y);
        WriteFixed(data, 16, z);
        return data;
    }

    private static byte[] TextTag(string text)
    {
        var bytes = Encoding.ASCII.GetBytes(text + '\0');
        var data = new byte[8 + bytes.Length];
        WriteUInt(data, 0, Signature("text"));
        bytes.CopyTo(data, 8);
        return data;
    }

    private static byte[] DescriptionTag(string text)
    {
        var bytes = Encoding.ASCII.GetBytes(text + '\0');
        var data = new byte[12 + bytes.Length + 78];
        WriteUInt(data, 0, Signature("desc"));
        WriteUInt(data, 8, (uint)bytes.Length);
        bytes.CopyTo(data, 12);
        return data;
    }

    private static byte[] MultilingualTextTag(string text)
    {
        var bytes = Encoding.BigEndianUnicode.GetBytes(text);
        var data = new byte[28 + bytes.Length];
        WriteUInt(data, 0, Signature("mluc"));
        WriteUInt(data, 8, 1);
        WriteUInt(data, 12, 12);
        WriteUInt(data, 16, Signature("enUS"));
        WriteUInt(data, 20, (uint)bytes.Length);
        WriteUInt(data, 24, 28);
        bytes.CopyTo(data, 28);
        return data;
    }

    private static double DecodeSrgb(double value) =>
        value <= 0.04045 ? value / 12.92 : Math.Pow((value + 0.055) / 1.055, 2.4);

    private static double[,] Identity() =>
        new double[,]
        {
            { 1, 0, 0 },
            { 0, 1, 0 },
            { 0, 0, 1 },
        };

    private static double[,] Multiply(double[,] left, double[,] right)
    {
        var result = new double[3, 3];
        for (var row = 0; row < 3; row++)
        for (var column = 0; column < 3; column++)
        for (var i = 0; i < 3; i++)
            result[row, column] += left[row, i] * right[i, column];
        return result;
    }

    private static double[,] Invert(double[,] matrix)
    {
        var a = matrix[0, 0];
        var b = matrix[0, 1];
        var c = matrix[0, 2];
        var d = matrix[1, 0];
        var e = matrix[1, 1];
        var f = matrix[1, 2];
        var g = matrix[2, 0];
        var h = matrix[2, 1];
        var i = matrix[2, 2];
        var determinant = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
        if (!double.IsFinite(determinant) || Math.Abs(determinant) < 1e-10)
            throw new InvalidDataException("The HDR color matrix is singular.");
        return new double[,]
        {
            {
                (e * i - f * h) / determinant,
                (c * h - b * i) / determinant,
                (b * f - c * e) / determinant,
            },
            {
                (f * g - d * i) / determinant,
                (a * i - c * g) / determinant,
                (c * d - a * f) / determinant,
            },
            {
                (d * h - e * g) / determinant,
                (b * g - a * h) / determinant,
                (a * e - b * d) / determinant,
            },
        };
    }

    private static void CheckRange(byte[] data, uint offset, int size)
    {
        if (offset < 36 || (long)offset + size > data.Length)
            throw new InvalidDataException("The existing MHC2 calibration data is truncated.");
    }

    private static int Align(int size) => checked((size + 3) & ~3);

    private static uint Signature(string text) =>
        BinaryPrimitives.ReadUInt32BigEndian(Encoding.ASCII.GetBytes(text));

    private static uint ReadUInt(ReadOnlySpan<byte> data, int offset) =>
        BinaryPrimitives.ReadUInt32BigEndian(data[offset..]);

    private static double ReadFixed(ReadOnlySpan<byte> data, int offset) =>
        BinaryPrimitives.ReadInt32BigEndian(data[offset..]) / 65536.0;

    private static void WriteUInt(Span<byte> data, int offset, uint value) =>
        BinaryPrimitives.WriteUInt32BigEndian(data[offset..], value);

    private static void WriteFixed(Span<byte> data, int offset, double value)
    {
        if (!double.IsFinite(value) || value < -32768 || value > 32767.99998)
            throw new InvalidDataException(
                "An HDR calibration value exceeds ICC fixed-point precision."
            );
        BinaryPrimitives.WriteInt32BigEndian(
            data[offset..],
            checked((int)Math.Round(value * 65536))
        );
    }
}
